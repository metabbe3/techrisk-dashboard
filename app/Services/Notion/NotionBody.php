<?php

declare(strict_types=1);

namespace App\Services\Notion;

/**
 * PROJ-018 round 7: Notion's fetch envelope renders blocks as unknown HTML
 * tags (<toggle>, <table-of-contents>, <meeting-notes>, …). Filament runs
 * every markdown/html entry through Symfony's HtmlSanitizer (safe elements
 * only), which drops unknown tags WITH their content — a Notion body would
 * render as just its first heading. Translating to standard HTML before
 * render keeps the whole body visible.
 */
class NotionBody
{
    public static function toHtml(string $markdown): string
    {
        // Round 12: give every toggle a POSITIONAL anchor (document order —
        // start tags appear outer-before-inner) so the rebuilt table of
        // contents can link to its section. Transient — the stored markdown
        // is never modified.
        $anchors = 0;
        $markdown = preg_replace_callback(
            '/<toggle heading="(h[1-6])">/',
            // By-reference capture — an arrow fn copies $anchors, every
            // toggle would get the same id.
            function (array $m) use (&$anchors): string {
                return '<toggle heading="'.$m[1].'" anchor="notion-sec-'.(++$anchors).'">';
            },
            $markdown,
        ) ?? $markdown;

        // Round 11: the <table-of-contents> widget is generated BY Notion
        // from the page's headings (a tool, never typed — the envelope
        // carries only the self-closing tag), so the portal rebuilds the
        // list from those same headings off the raw markdown (document
        // order) and writes it where the tag stood. No headings → nothing.
        $toc = self::renderToc(self::collectHeadings($markdown));

        // Toggles carry their title on the line(s) before the first blank
        // line, then the children as siblings. Convert innermost-first — a
        // toggle can nest a toggle — until none are left. Owner 2026-11-04:
        // the portal renders each toggle as a collapsible <details> (open by
        // default so nothing looks missing; the summary hides/unhides it).
        do {
            $before = $markdown;
            $markdown = preg_replace_callback(
                '/<toggle heading="(h[1-6])"(?: anchor="([^"]+)")?>((?:(?!<toggle[\s>]|<\/toggle>)[\s\S])*)<\/toggle>/',
                function (array $m): string {
                    $inner = ltrim($m[3]);

                    if (preg_match('/\A(.*?)\n\s*\n([\s\S]*)\z/s', $inner, $parts)) {
                        $heading = trim($parts[1]);
                        $children = trim($parts[2]);
                    } else {
                        $heading = trim($inner);
                        $children = '';
                    }

                    // Round 12 (owner: "sesuaikan font, style, seperti bagian
                    // lain, seperti pada Root Cause Analysis"): the title is
                    // a REAL heading — the infolist entry's prose styles
                    // (the same ones that style the RCA section's markdown)
                    // supply the typography; only the indent ladder
                    // (round 10) stays a class. A summary may carry exactly
                    // one heading element per the HTML spec.
                    //
                    // Round 14 (owner: the marker must sit ON the title's
                    // line, VERTICALLY CENTERED — "misal jika tinggi font 11
                    // maka posisi toggle di 6", later "should be vertically
                    // centered" — and COLORED, good in light AND dark): the
                    // native marker (position uncontrollable) is replaced by
                    // an indigo triangle (the panel primary, reads on both
                    // themes) living INSIDE the heading as an inline element
                    // with `vertical-align: middle` — centered against the
                    // TEXT itself, so it holds at every heading size; a
                    // flex-centered span rode the line box (incl. descender
                    // space) and sat visibly low on big headings. It points
                    // right when closed and rotates down via the
                    // `group-open:` variant on the details' `group` class.
                    // The body content stays selectable (round 13).
                    //
                    // The trailing `!` is NOT decoration: Filament ships an
                    // UNLAYERED Tailwind 3 preflight (`summary
                    // {display:list-item}`, `* {border-width:0;…}`) that
                    // beats every @layer-ed utility of the app build at any
                    // specificity — unlayered author styles win the cascade.
                    // The colliding classes must be important or the marker
                    // renders as nothing at all.
                    $tag = $m[1];
                    $pad = self::pad((int) substr($tag, 1));
                    // `flex!` on the summary removes the list-item box Filament's
                    // preflight forces on <summary> — keep it or every browser
                    // paints its NATIVE gray marker next to the indigo one.
                    $summary = '<summary class="flex! cursor-pointer">'
                        .'<'.$tag.($pad !== '' ? ' class="'.$pad.'"' : '').'>'
                        .'<span class="mr-1.5 inline-block h-0! w-0! border-y-4! border-y-transparent! border-l-[6px]! border-l-indigo-500! align-middle transition-transform group-open:rotate-90"></span>'
                        .preg_replace('/\s+/m', ' ', $heading ?? '').'</'.$tag.'></summary>';

                    // Round 11 (owner: "atur line-height, beautify"): wider
                    // separation between sections; the prose styles do the
                    // rest. The id is the rebuilt TOC's link target.
                    return '<details'.($m[2] !== null && $m[2] !== '' ? ' id="'.$m[2].'"' : '')
                        .' class="group my-5" open>'.$summary
                        .($children !== '' ? "\n\n".$children."\n\n" : '').'</details>';
                },
                $markdown,
            ) ?? $markdown;
        } while ($markdown !== $before);

        // A leftover toggle wrapper without a heading unwraps — keep children.
        $markdown = preg_replace('#</?toggle[^>]*>#', '', $markdown) ?? $markdown;

        // Round 10: a KEPT (un-generated) ai_block placeholder renders as a
        // visible note — unwrapping it left the section empty even though
        // Notion has an AI block there waiting to be run (RCA / MOM /
        // Invitation — the blocks that later carry the generated tables).
        $markdown = preg_replace(
            '#<unknown\s[^>]*alt="ai_block"[^>]*/?>#',
            '<p class="text-sm text-gray-500 italic">AI block — not generated in Notion yet. Run it there, then Refresh.</p>',
            $markdown,
        ) ?? $markdown;

        // Round 10 (probe): apply_template copies the template's file
        // attachments, but a `notion-file-block://` source cannot be linked
        // from the portal — name the attachment instead of silently dropping
        // the unknown tag in the sanitizer.
        $markdown = preg_replace_callback(
            '#<file\s[^>]*source="([^"]*)"[^>]*/?>#',
            function (array $m): string {
                // The name is a query param inside the source URL, not a
                // standalone attribute (`…&name=investigation_plan.md`).
                $name = preg_match('/[?&]name=([^&"]+)/', $m[1], $n) ? $n[1] : 'attachment';

                return '<p class="text-sm text-gray-500">Attachment (in Notion): '.$name.'</p>';
            },
            $markdown,
        ) ?? $markdown;

        // Notion UI widgets/containers: the TOC is replaced by the rebuilt
        // list (empty when there are no headings — nothing written), the
        // rest unwrap around real content.
        $markdown = preg_replace_callback(
            '#<table-of-contents[^>]*>(?:[\s\S]*?</table-of-contents>)?#',
            fn () => $toc,
            $markdown,
        ) ?? $markdown;
        $markdown = preg_replace('#<(/?)(meeting-notes(?:-section-notes)?|unknown|date|bookmark|callout)[^>]*/?>#', '', $markdown) ?? $markdown;

        return $markdown;
    }

    /**
     * Round 10: the heading ladder both the section summaries and the
     * rebuilt table of contents indent by — the deeper the hierarchy, the
     * further right the title sits.
     */
    private static function pad(int $level): string
    {
        return match (true) {
            $level <= 1 => '',
            $level === 2 => 'pl-4',
            $level === 3 => 'pl-8',
            default => 'pl-12',
        };
    }

    /**
     * The headings the portal table of contents lists: toggle titles and
     * bare markdown headings, in document order (one combined scan so the
     * two kinds interleave correctly), minus the TOC's own heading. Only
     * each toggle's FIRST line is listed — multi-line titles are the rare
     * exception, and the section summaries carry the full text. Toggle
     * entries carry their positional anchor (round 12) so they link to the
     * section; bare markdown headings have no anchorable element.
     *
     * @return array<int, array{level: int, text: string, anchor: ?string}>
     */
    private static function collectHeadings(string $markdown): array
    {
        preg_match_all(
            '/<toggle heading="h([1-6])"(?: anchor="([^"]+)")?>\s*([^\n]+)|^(#{1,6})[ \t]+(\S[^\n]*)/m',
            $markdown,
            $matches,
            PREG_SET_ORDER,
        );

        $headings = [];

        foreach ($matches as $m) {
            // The unmatched alternative's groups come back as '' (never null).
            $isToggle = $m[2] !== '';
            $level = $isToggle ? (int) $m[1] : strlen((string) $m[4]);
            $text = trim($isToggle ? $m[3] : (string) $m[5]);

            // The TOC never lists itself, and a tag-looking first line is an
            // empty-titled toggle's child — not a heading.
            if ($text === '' || str_starts_with($text, '<') || preg_match('/^table of contents?$/i', $text) === 1) {
                continue;
            }

            $headings[] = ['level' => $level, 'text' => $text, 'anchor' => $isToggle ? $m[2] : null];
        }

        return $headings;
    }

    /**
     * @param  array<int, array{level: int, text: string, anchor: ?string}>  $headings
     */
    private static function renderToc(array $headings): string
    {
        if ($headings === []) {
            return '';
        }

        $items = implode("\n", array_map(
            function (array $h): string {
                $pad = self::pad($h['level']);
                // Round 12: toggle entries link to their section (the
                // sanitizer keeps the id and fragment href, probed).
                $text = $h['anchor'] !== null && $h['anchor'] !== ''
                    ? '<a href="#'.$h['anchor'].'">'.$h['text'].'</a>'
                    : $h['text'];

                return ($pad !== '' ? '<li class="'.$pad.'">' : '<li>').$text.'</li>';
            },
            $headings,
        ));

        // One line, no blank lines inside — the whole list stays a single
        // HTML block, so the markdown pass leaves the entries untouched.
        // `list-none!`/`p-0!` must be important: Filament's unlayered
        // preflight + prose styles re-add bullets/padding to lists.
        return '<div class="text-sm"><ul class="list-none! space-y-1 p-0!">'.$items.'</ul></div>';
    }
}
